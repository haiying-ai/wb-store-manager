from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path
from typing import Any

from .client import WbApiError, WbClient
from .endpoints import ApiDomain
from .paths import CategoryPaths
from .sku_alias import canonical_sku


BARCODE_ENDPOINT = f"{ApiDomain.CONTENT}/content/v2/barcodes"


def generate_official_barcodes(client: WbClient, *, count: int = 1) -> list[str]:
    if count < 1 or count > 5000:
        raise ValueError("WB barcode generation count must be between 1 and 5000.")
    result = client.request("POST", BARCODE_ENDPOINT, body={"count": count})
    if not result.ok:
        raise WbApiError("WB barcode generation failed.", status=result.status, body=result.data)
    barcodes = _extract_barcodes(result.data)
    if len(barcodes) < count:
        raise WbApiError(f"WB returned {len(barcodes)} barcodes, expected {count}.", status=result.status, body=result.data)
    return barcodes[:count]


def attach_barcode_to_manual_overrides(paths: CategoryPaths, sku: str, barcode: str, *, source: str = "WB official API /content/v2/barcodes") -> Path:
    sku = canonical_sku(sku, category=paths.category)
    path = paths.kb / "manual_overrides.json"
    data = _read_json(path, default={"products": {}})
    product = data.setdefault("products", {}).setdefault(sku, {"fields": {}})
    fields = product.setdefault("fields", {})
    fields["barcode"] = barcode
    fields["barcodeSource"] = {
        "source": source,
        "generatedAt": datetime.now().isoformat(timespec="seconds"),
        "wbEndpoint": "/content/v2/barcodes",
        "wbCardField": "sizes[].skus[]",
    }
    notes = product.setdefault("notes", [])
    notes.append(f"Barcode {barcode} generated by WB official API and attached to {sku}.")
    _write_json(path, data)
    return path


def generate_and_attach_barcode(client: WbClient, paths: CategoryPaths, sku: str) -> dict[str, Any]:
    barcode = generate_official_barcodes(client, count=1)[0]
    path = attach_barcode_to_manual_overrides(paths, sku, barcode)
    return {
        "sku": canonical_sku(sku, category=paths.category),
        "barcode": barcode,
        "manualOverrides": str(path),
        "source": "WB official API /content/v2/barcodes",
        "nextStep": "Run `python -m wb_manager kb sync --category <category>` and regenerate the product confirmation package.",
    }


def _extract_barcodes(data: Any) -> list[str]:
    if isinstance(data, list):
        return [str(item) for item in data if str(item).strip()]
    if isinstance(data, dict):
        for key in ("data", "barcodes", "skus"):
            value = data.get(key)
            if isinstance(value, list):
                return [str(item) for item in value if str(item).strip()]
    return []


def _read_json(path: Path, *, default: Any) -> Any:
    if not path.exists():
        return default
    return json.loads(path.read_text(encoding="utf-8-sig"))


def _write_json(path: Path, data: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
